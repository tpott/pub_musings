#!/usr/bin/env python3
"""
Evaluate Whisper transcription accuracy against test corpus.

Usage:
  python evaluate.py                    # Evaluate all seeds against whisper-server
  python evaluate.py --seed english-basic  # Evaluate specific seed
  python evaluate.py --list             # List available seeds

Requirements:
  pip install PyYAML jiwer requests

Expects:
  - Audio files generated by generate.sh
  - whisper-server running (default: http://localhost:8765)
"""

import argparse
import json
import os
import sys
import time
from datetime import datetime
from pathlib import Path
from typing import Optional

import requests
import yaml

# Try to import jiwer for WER calculation
try:
    from jiwer import wer, cer
    HAS_JIWER = True
except ImportError:
    HAS_JIWER = False
    print("Warning: jiwer not installed. Install with: pip install jiwer")
    print("WER calculation will be skipped.")


SCRIPT_DIR = Path(__file__).parent
SEEDS_DIR = SCRIPT_DIR / "seeds"
AUDIO_DIR = SCRIPT_DIR / "audio"
RESULTS_DIR = SCRIPT_DIR / "results"

# Default whisper-server URL
DEFAULT_WHISPER_URL = os.environ.get("WHISPER_URL", "http://localhost:8765")


def load_seed(seed_id: str) -> dict:
    """Load a seed YAML file."""
    seed_file = SEEDS_DIR / f"{seed_id}.yaml"
    if not seed_file.exists():
        raise FileNotFoundError(f"Seed file not found: {seed_file}")
    with open(seed_file) as f:
        return yaml.safe_load(f)


def list_seeds() -> list[str]:
    """List available seed IDs."""
    return [f.stem for f in SEEDS_DIR.glob("*.yaml")]


def transcribe_audio(audio_path: Path, whisper_url: str, language: str = "en") -> dict:
    """Send audio to whisper-server and get transcription."""
    with open(audio_path, "rb") as f:
        files = {"file": (audio_path.name, f, "audio/wav")}
        data = {"language": language}

        response = requests.post(
            f"{whisper_url}/transcribe",
            files=files,
            data=data,
            timeout=120
        )
        response.raise_for_status()
        return response.json()


def calculate_wer_score(reference: str, hypothesis: str) -> Optional[float]:
    """Calculate Word Error Rate between reference and hypothesis."""
    if not HAS_JIWER:
        return None

    # Normalize text for comparison
    ref_normalized = reference.lower().strip()
    hyp_normalized = hypothesis.lower().strip()

    if not ref_normalized:
        return 0.0 if not hyp_normalized else 1.0

    return wer(ref_normalized, hyp_normalized)


def calculate_cer_score(reference: str, hypothesis: str) -> Optional[float]:
    """Calculate Character Error Rate between reference and hypothesis."""
    if not HAS_JIWER:
        return None

    ref_normalized = reference.lower().strip()
    hyp_normalized = hypothesis.lower().strip()

    if not ref_normalized:
        return 0.0 if not hyp_normalized else 1.0

    return cer(ref_normalized, hyp_normalized)


def evaluate_segment(
    segment: dict,
    audio_path: Path,
    whisper_url: str,
    language: str
) -> dict:
    """Evaluate a single segment."""
    reference_text = segment.get("text", "")
    segment_id = segment.get("id", "unknown")

    if not audio_path.exists():
        return {
            "id": segment_id,
            "status": "error",
            "error": f"Audio file not found: {audio_path}"
        }

    try:
        start_time = time.time()
        result = transcribe_audio(audio_path, whisper_url, language)
        processing_time = time.time() - start_time

        hypothesis_text = result.get("text", "").strip()
        audio_duration = result.get("duration", 0)

        # Calculate metrics
        wer_score = calculate_wer_score(reference_text, hypothesis_text)
        cer_score = calculate_cer_score(reference_text, hypothesis_text)

        rtf = processing_time / audio_duration if audio_duration > 0 else None

        return {
            "id": segment_id,
            "status": "success",
            "reference": reference_text,
            "hypothesis": hypothesis_text,
            "wer": wer_score,
            "cer": cer_score,
            "processing_time_seconds": round(processing_time, 3),
            "audio_duration_seconds": round(audio_duration, 3),
            "rtf": round(rtf, 4) if rtf else None,
            "detected_language": result.get("language")
        }

    except requests.exceptions.RequestException as e:
        return {
            "id": segment_id,
            "status": "error",
            "error": str(e)
        }
    except Exception as e:
        return {
            "id": segment_id,
            "status": "error",
            "error": str(e)
        }


def evaluate_seed(seed_id: str, whisper_url: str) -> dict:
    """Evaluate all segments in a seed."""
    seed = load_seed(seed_id)
    language = seed.get("language", "en")
    segments = seed.get("segments", [])
    audio_dir = AUDIO_DIR / seed_id

    results = []
    for segment in segments:
        segment_id = segment.get("id", "segment")
        audio_path = audio_dir / f"{segment_id}.wav"

        print(f"  Evaluating {segment_id}...", end=" ", flush=True)
        result = evaluate_segment(segment, audio_path, whisper_url, language)
        results.append(result)

        if result["status"] == "success":
            wer_str = f"WER={result['wer']:.2%}" if result['wer'] is not None else "WER=N/A"
            print(f"{wer_str}, RTF={result['rtf']:.3f}")
        else:
            print(f"ERROR: {result['error']}")

    # Calculate summary statistics
    successful = [r for r in results if r["status"] == "success"]
    summary = {
        "seed_id": seed_id,
        "language": language,
        "total_segments": len(segments),
        "successful_segments": len(successful),
        "failed_segments": len(results) - len(successful)
    }

    if successful:
        wer_values = [r["wer"] for r in successful if r["wer"] is not None]
        rtf_values = [r["rtf"] for r in successful if r["rtf"] is not None]
        processing_times = [r["processing_time_seconds"] for r in successful]
        audio_durations = [r["audio_duration_seconds"] for r in successful]

        if wer_values:
            summary["average_wer"] = round(sum(wer_values) / len(wer_values), 4)
            summary["min_wer"] = round(min(wer_values), 4)
            summary["max_wer"] = round(max(wer_values), 4)

        if rtf_values:
            summary["average_rtf"] = round(sum(rtf_values) / len(rtf_values), 4)

        summary["total_processing_time"] = round(sum(processing_times), 3)
        summary["total_audio_duration"] = round(sum(audio_durations), 3)

    return {
        "summary": summary,
        "segments": results
    }


def save_results(results: dict, output_path: Optional[Path] = None):
    """Save evaluation results to JSON file."""
    RESULTS_DIR.mkdir(exist_ok=True)

    if output_path is None:
        timestamp = datetime.now().strftime("%Y-%m-%d_%H%M%S")
        output_path = RESULTS_DIR / f"{timestamp}.json"

    with open(output_path, "w") as f:
        json.dump(results, f, indent=2)

    # Also create/update latest.json symlink
    latest_path = RESULTS_DIR / "latest.json"
    if latest_path.exists():
        latest_path.unlink()
    with open(latest_path, "w") as f:
        json.dump(results, f, indent=2)

    return output_path


def print_summary(results: dict):
    """Print evaluation summary."""
    print("\n" + "=" * 60)
    print("EVALUATION SUMMARY")
    print("=" * 60)

    for seed_result in results.get("seeds", []):
        summary = seed_result.get("summary", {})
        print(f"\n{summary.get('seed_id', 'unknown')} ({summary.get('language', '?')}):")
        print(f"  Segments: {summary.get('successful_segments', 0)}/{summary.get('total_segments', 0)} successful")

        if "average_wer" in summary:
            print(f"  Average WER: {summary['average_wer']:.2%}")
            print(f"  WER Range: {summary['min_wer']:.2%} - {summary['max_wer']:.2%}")

        if "average_rtf" in summary:
            print(f"  Average RTF: {summary['average_rtf']:.3f}x")

        if "total_processing_time" in summary:
            print(f"  Total Time: {summary['total_processing_time']:.1f}s processing / {summary['total_audio_duration']:.1f}s audio")


def main():
    parser = argparse.ArgumentParser(
        description="Evaluate Whisper transcription accuracy"
    )
    parser.add_argument(
        "--seed",
        type=str,
        help="Evaluate specific seed (default: all seeds)"
    )
    parser.add_argument(
        "--list",
        action="store_true",
        help="List available seeds"
    )
    parser.add_argument(
        "--whisper-url",
        type=str,
        default=DEFAULT_WHISPER_URL,
        help=f"Whisper server URL (default: {DEFAULT_WHISPER_URL})"
    )
    parser.add_argument(
        "--output",
        type=str,
        help="Output JSON file path (default: results/<timestamp>.json)"
    )

    args = parser.parse_args()

    if args.list:
        seeds = list_seeds()
        print("Available seeds:")
        for seed in seeds:
            print(f"  - {seed}")
        return 0

    # Check whisper-server connectivity
    print(f"Checking whisper-server at {args.whisper_url}...")
    try:
        response = requests.get(f"{args.whisper_url}/health", timeout=5)
        if response.status_code != 200:
            print(f"Warning: Health check returned status {response.status_code}")
    except requests.exceptions.RequestException as e:
        print(f"Error: Cannot connect to whisper-server: {e}")
        print("Make sure whisper-server is running and accessible.")
        return 1

    print("Connected successfully.\n")

    # Determine which seeds to evaluate
    if args.seed:
        seed_ids = [args.seed]
    else:
        seed_ids = list_seeds()

    if not seed_ids:
        print("No seeds found in evaluation/seeds/")
        return 1

    # Run evaluation
    results = {
        "timestamp": datetime.now().isoformat(),
        "whisper_url": args.whisper_url,
        "seeds": []
    }

    for seed_id in seed_ids:
        print(f"Evaluating seed: {seed_id}")
        try:
            seed_result = evaluate_seed(seed_id, args.whisper_url)
            results["seeds"].append(seed_result)
        except FileNotFoundError as e:
            print(f"  Error: {e}")
            continue
        except Exception as e:
            print(f"  Error: {e}")
            continue

    # Save and print results
    output_path = Path(args.output) if args.output else None
    saved_path = save_results(results, output_path)
    print(f"\nResults saved to: {saved_path}")

    print_summary(results)

    return 0


if __name__ == "__main__":
    sys.exit(main())
